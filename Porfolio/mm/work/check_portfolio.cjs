const fs = require("fs");
const path = require("path");
const root = path.resolve("outputs");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8").replace(/^\uFEFF/, "");
const css = fs.readFileSync(path.join(root, "style.css"), "utf8").replace(/^\uFEFF/, "");
const js = fs.readFileSync(path.join(root, "script.js"), "utf8").replace(/^\uFEFF/, "");
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
const idSet = new Set(ids);
const duplicateIds = [...new Set(ids.filter((id, i) => ids.indexOf(id) !== i))];
const hrefs = [...html.matchAll(/\bhref="([^"]*)"/g)].map((m) => m[1]);
const brokenAnchors = [...new Set(hrefs.filter((h) => h.startsWith("#") && !idSet.has(h.slice(1))))];
const localRefs = [...new Set(hrefs.filter((h) => h && !/^(#|https?:|mailto:|tel:)/.test(h)))];
const missingFiles = localRefs.filter((ref) => !fs.existsSync(path.join(root, ref.split("#")[0])));
const labels = [...html.matchAll(/\bfor="([^"]+)"/g)].map((m) => m[1]);
const missingLabels = [...new Set(labels.filter((id) => !idSet.has(id)))];
const controls = [...html.matchAll(/\baria-controls="([^"]+)"/g)].map((m) => m[1]);
const missingControls = [...new Set(controls.filter((id) => !idSet.has(id)))];
const jsIds = [...js.matchAll(/getElementById\("([^"]+)"\)/g)].map((m) => m[1]);
const missingJsIds = [...new Set(jsIds.filter((id) => !idSet.has(id)))];
const media = ["@media(max-width:980px)", "@media(max-width:700px)", "@media(max-width:390px)", "prefers-reduced-motion"].every((x) => css.includes(x));
const landmarks = ["<header", "<nav", "<main", "<footer"].every((x) => html.includes(x));
console.log("Duplicate IDs:", duplicateIds);
console.log("Broken section links:", brokenAnchors);
console.log("Missing local link targets:", missingFiles);
console.log("Missing form label/control targets:", missingLabels, missingControls);
console.log("JavaScript references to missing elements:", missingJsIds);
console.log("Responsive breakpoints and reduced-motion CSS:", media);
console.log("Semantic page landmarks:", landmarks);
console.log("Contact endpoint unset by default:", /formEndpoint:\s*""/.test(js));
if (duplicateIds.length || brokenAnchors.length || missingFiles.length || missingLabels.length || missingControls.length || missingJsIds.length || !media || !landmarks) process.exit(1);
